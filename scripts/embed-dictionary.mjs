#!/usr/bin/env node
/**
 * embed-dictionary.mjs
 * --------------------
 * Reads the Hunspell `.aff` / `.dic` files from the installed `dictionary-en`
 * package, gzip-compresses them, base64-encodes the result, and emits a
 * self-contained ES module (`src/generated/dict-data.ts`) that decodes the data
 * back into `{ aff, dic }` at load time using Node's built-in `zlib`.
 *
 * This lets esbuild inline the dictionary into a single `dist/tui.mjs`, so the
 * plugin needs no runtime `bun install` and no on-disk dictionary files.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { gzipSync } from "node:zlib"
import { fileURLToPath } from "node:url"
import path from "node:path"

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, "..")

function findDict(pkg, name) {
  const candidates = [
    path.join(root, "node_modules", pkg, name),
    path.join(root, "..", "node_modules", pkg, name),
  ]
  for (const c of candidates) {
    try {
      return readFileSync(c)
    } catch {
      /* try next */
    }
  }
  throw new Error(
    `Could not find ${pkg}/${name}. Run \`npm install ${pkg}\` first.`,
  )
}

const dicts = [
  { pkg: "dictionary-ru", aff: findDict("dictionary-ru", "index.aff"), dic: findDict("dictionary-ru", "index.dic") },
  { pkg: "dictionary-en", aff: findDict("dictionary-en", "index.aff"), dic: findDict("dictionary-en", "index.dic") },
]

const entries = dicts.map((d, i) => {
  const affB64 = gzipSync(d.aff, { level: 9 }).toString("base64")
  const dicB64 = gzipSync(d.dic, { level: 9 }).toString("base64")
  return { affB64, dicB64, affSize: d.aff.length, dicSize: d.dic.length, affGz: Buffer.byteLength(affB64, "base64"), dicGz: Buffer.byteLength(dicB64, "base64") }
})

const out = `/* AUTO-GENERATED by scripts/embed-dictionary.mjs — do not edit. */
/* eslint-disable */
import { gunzipSync } from "node:zlib"

${entries.map((e, i) => `const AFF_${i}_GZ_B64 = ${JSON.stringify(e.affB64)}
const DIC_${i}_GZ_B64 = ${JSON.stringify(e.dicB64)}`).join("\n\n")}

function decode(b64: string): Buffer {
  return gunzipSync(Buffer.from(b64, "base64"))
}

export const embeddedDictionaries = [
${entries.map((_, i) => `  {
    get aff(): Buffer { return decode(AFF_${i}_GZ_B64) },
    get dic(): Buffer { return decode(DIC_${i}_GZ_B64) },
  }`).join(",\n")}
]
`

const outDir = path.join(root, "src", "generated")
mkdirSync(outDir, { recursive: true })
writeFileSync(path.join(outDir, "dict-data.ts"), out, "utf8")

const kb = (n) => (n / 1024).toFixed(0)
entries.forEach((e, i) => {
  console.log(
    `embedded ${dicts[i].pkg} → src/generated/dict-data.ts  ` +
      `(aff ${kb(e.affSize)}KB→${kb(e.affGz)}KB gz, ` +
      `dic ${kb(e.dicSize)}KB→${kb(e.dicGz)}KB gz)`,
  )
})
